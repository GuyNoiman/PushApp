#!/usr/bin/env node
/**
 * Writes `console/config.js` from the app's own `.env`.
 *
 * The console needs the same two client-safe values the app already has, and
 * copying them by hand is how two files start disagreeing about which Supabase
 * project is live. This reads the one that already exists.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appDir = join(here, '..');
const envPath = join(appDir, '.env');
const outPath = join(appDir, 'console', 'config.js');

if (!existsSync(envPath)) {
  console.error(`No .env at ${envPath}. Copy .env.example and fill it in first.`);
  process.exit(1);
}

const env = Object.fromEntries(
  readFileSync(envPath, 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => {
      const i = line.indexOf('=');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    }),
);

const url = env.EXPO_PUBLIC_SUPABASE_URL;
const key = env.EXPO_PUBLIC_SUPABASE_ANON_KEY;
if (!url || !key) {
  console.error('.env is missing EXPO_PUBLIC_SUPABASE_URL or EXPO_PUBLIC_SUPABASE_ANON_KEY.');
  process.exit(1);
}

writeFileSync(
  outPath,
  `// Generated by scripts/write-console-config.mjs. Do not edit; do not commit.\n` +
    `window.PUSHAPP_CONSOLE = {\n  supabaseUrl: ${JSON.stringify(url)},\n  supabaseAnonKey: ${JSON.stringify(key)},\n};\n`,
);

console.log(`Wrote ${outPath} for ${url}`);
