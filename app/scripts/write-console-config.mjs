#!/usr/bin/env node
/**
 * Writes the config file for every static web surface from the app's own `.env`.
 *
 * Each site needs the same two client-safe values the app already has, and
 * copying them by hand is how three files start disagreeing about which Supabase
 * project is live. This reads the one that already exists.
 *
 * The filename and the `console:config` npm script keep their original names on
 * purpose even though this now writes the studio's file too: `packageJson:scripts`
 * is a runtime-fingerprint source, so renaming the script would invalidate every
 * installed build and cut it off from over-the-air updates. It is worth renaming
 * at the next native build, and not worth a build of its own.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appDir = join(here, '..');
const envPath = join(appDir, '.env');
const targets = [
  { dir: 'console', global: 'PUSHAPP_CONSOLE' },
  { dir: 'creator', global: 'PUSHAPP_STUDIO' },
];

if (!existsSync(envPath)) {
  console.error(`No .env at ${envPath}. Copy .env.example and fill it in first.`);
  process.exit(1);
}

const env = Object.fromEntries(
  readFileSync(envPath, 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => {
      const i = line.indexOf('=');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    }),
);

const url = env.EXPO_PUBLIC_SUPABASE_URL;
const key = env.EXPO_PUBLIC_SUPABASE_ANON_KEY;
if (!url || !key) {
  console.error('.env is missing EXPO_PUBLIC_SUPABASE_URL or EXPO_PUBLIC_SUPABASE_ANON_KEY.');
  process.exit(1);
}

for (const { dir, global } of targets) {
  const outPath = join(appDir, dir, 'config.js');
  if (!existsSync(join(appDir, dir))) continue;
  writeFileSync(
    outPath,
    `// Generated by scripts/write-console-config.mjs. Do not edit; do not commit.\n` +
      `window.${global} = {\n  supabaseUrl: ${JSON.stringify(url)},\n  supabaseAnonKey: ${JSON.stringify(key)},\n};\n`,
  );
  console.log(`Wrote ${outPath} for ${url}`);
}
